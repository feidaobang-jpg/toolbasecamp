import assert from 'node:assert/strict';
import { createRun, createWorld, step, qa } from '../../../public/html/game/tank-3d/sim.js';
import { snapshot, hydrate } from '../../../public/html/game/tank-3d/coop.js';
const idle = { players: [{ dir: -1 }, { dir: -1 }] };
const run = createRun({ coop: true, seed: 12, armor: 'std' });
const w = createWorld(run);
for (let i = 0; i < 40; i++) step(w, idle);
assert.equal(w.seats.length, 2);
const [a, b] = w.seats.map(s => s.tank);
assert(a && b && a.id !== b.id);
assert.equal(a.x, 64); assert.equal(b.x, 128);
for (const values of Object.values(w.terrain)) values.fill(0);
w.bots = []; w.rosterIndex = w.roster.length; w.remaining = 99;
for (let i = 0; i < 20; i++) step(w, { players: [{ dir: 0 }, { dir: 0, firePressed: i === 0 }] });
assert(a.y < 192 && b.y < 192);
assert(w.playerShots >= 1, 'guest fires on host simulation');
assert.equal(w.bullets[0].owner, b);
const guest = createWorld(createRun({ coop: true, seed: 12 }));
hydrate(guest, JSON.parse(JSON.stringify(snapshot(w))), 1);
assert.equal(guest.seats[1].tank.x, b.x);
assert.equal(guest.bullets[0].owner, guest.seats[1].tank);
assert(guest.terrain.brick instanceof Uint8Array);
assert.equal(guest.localSlot, 1);
// Enemy bullets hit the correct player, leaving the other player's HP untouched.
b.shield = b.invuln = 0;
w.bullets = [{ id: w.nextId++, team: 'bot', owner: {}, state: 'fly', x: b.x + 8, y: b.y + 8, vx: 0, vy: 0, speed: 1, dir: 0, kind: 'shell', age: 0 }];
step(w, idle);
assert.equal(w.seats[1].state.hp, 2); assert.equal(w.seats[0].state.hp, 3);
// One exhausted seat does not end the match while the teammate is alive.
w.seats[1].state.lives = 1; b.invuln = b.shield = 0;
w.seats[1].state.hp = 1;
w.bullets = [{ id: w.nextId++, team: 'bot', owner: {}, state: 'fly', x: b.x + 8, y: b.y + 8, vx: 0, vy: 0, speed: 1, dir: 0, kind: 'shell', age: 0 }];
for (let i = 0; i < 35; i++) step(w, idle);
assert.equal(w.seats[1].state.lives, 0);
assert.equal(w.seats[1].tank, null);
assert.equal(w.status, 'play');
w.player = a; qa.killPlayer(w); w.seats[0].state.lives = 1;
for (let i = 0; i < 35; i++) step(w, idle);
assert.equal(w.status, 'gameover');
// Infinite lives survive JSON transport and stage transitions.
const inf = createWorld(createRun({ coop: true, lives: 'inf' }));
const copy = createWorld(createRun({ coop: true, lives: 'inf' }));
hydrate(copy, JSON.parse(JSON.stringify(snapshot(inf))), 1);
assert.equal(copy.seats[1].state.lives, Infinity);
// Both seats retain score bonus lives and carry their own equipment into a new stage.
const bonus = createWorld(createRun({ coop: true, seed: 4 }));
for (let i = 0; i < 40; i++) step(bonus, idle);
bonus.run.score = 19950;
const enemy = qa.spawnBot(bonus, 'basic', 40, 40, 16, false);
qa.destroyBot(bonus, enemy, false);
step(bonus, idle);
assert.deepEqual(bonus.seats.map(s => s.state.lives), [4, 4]);
bonus.seats[1].state.stars = 2;
bonus.run.stage = 2;
const next = createWorld(bonus.run);
for (let i = 0; i < 40; i++) step(next, idle);
assert.equal(next.seats[1].tank.stars, 2);
assert.equal(next.seats[1].state.lives, 4);
console.log('PASS: two players move/fire, snapshots retain ownership and terrain, independent damage/lives, shared loss and infinite lives');
